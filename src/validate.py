"""
validate.py - Run every data-quality check, record the results, write the report.

WHAT IT PRODUCES
1. qa.check_results  - one row per check per run (history: you can see whether
                        an issue is growing between runs)
2. docs/data_quality_report.md - the human-readable report
3. Exit code 0 if nothing FAILED, 1 otherwise, so a pipeline can stop before
   building analysis on bad data ("fail fast").

STATUS RULES (see evaluate() - it's a pure function, tested in tests/)
    no violations                          -> PASS
    severity error, any violation          -> FAIL
    severity warn, rate > fail_above_pct   -> FAIL  (known issue got worse)
    severity warn, otherwise               -> WARN  (known, documented, tolerated)
    severity info                          -> INFO  (context, never fails)
    the check's SQL itself crashed         -> FAIL  (a broken check must never
                                                     look like a passing one)

Usage:
    python src/validate.py
"""

from __future__ import annotations

import sys
import uuid
from dataclasses import dataclass
from datetime import datetime
from decimal import Decimal

from checks import CHECKS, Check
from config import DB_PATH, DOCS_DIR, connect_db

REPORT_PATH = DOCS_DIR / "data_quality_report.md"
ICON = {"PASS": "✅", "WARN": "⚠️", "FAIL": "❌", "INFO": "ℹ️"}


@dataclass
class Result:
    check: Check
    violations: int
    total: int
    amount: Decimal | None
    detail: str | None
    status: str

    @property
    def pct(self) -> float | None:
        # A % only makes sense when the denominator is a row count (> 1).
        return 100.0 * self.violations / self.total if self.total and self.total > 1 else None


def evaluate(check: Check, violations: int, total: int) -> str:
    """Turn raw counts into a status. Pure: no database, easy to test."""
    if check.severity not in {"error", "warn", "info"}:
        raise ValueError(f"unknown severity {check.severity!r} on {check.id}")
    if check.severity == "info":
        return "INFO"
    if violations == 0:
        return "PASS"
    if check.severity == "error":
        return "FAIL"
    pct = 100.0 * violations / total if total else 100.0
    if check.fail_above_pct is not None and pct > check.fail_above_pct:
        return "FAIL"
    return "WARN"


def run_check(con, check: Check) -> Result:
    try:
        cur = con.execute(check.sql)
        cols = [d[0] for d in cur.description]
        row = dict(zip(cols, cur.fetchone() or (0, 0, None, "no rows")))
        violations = int(row.get("violations") or 0)
        total = int(row.get("total") or 0)
        status = evaluate(check, violations, total)
        return Result(check, violations, total, row.get("amount"), row.get("detail"), status)
    except Exception as exc:  # report it; never silently skip a check
        return Result(check, 0, 0, None, f"check crashed: {exc}", "FAIL")


def save_history(con, run_id: str, run_at: datetime, results: list[Result]) -> None:
    con.execute("CREATE SCHEMA IF NOT EXISTS qa")
    con.execute("""
        CREATE TABLE IF NOT EXISTS qa.check_results (
            run_id VARCHAR, run_at TIMESTAMP, check_id VARCHAR, category VARCHAR,
            table_name VARCHAR, severity VARCHAR, status VARCHAR,
            violations BIGINT, total BIGINT, pct DOUBLE,
            amount DECIMAL(18,2), detail VARCHAR
        )""")
    con.executemany(
        "INSERT INTO qa.check_results VALUES (?,?,?,?,?,?,?,?,?,?,?,?)",
        [(run_id, run_at, r.check.id, r.check.category, r.check.table, r.check.severity,
          r.status, r.violations, r.total, r.pct, r.amount, r.detail) for r in results],
    )


# ---------------------------------------------------------------------------
# Report
# ---------------------------------------------------------------------------

def _n(x) -> str:
    return f"{x:,}"


def _pct(r: Result) -> str:
    return "" if r.pct is None else f"{r.pct:.2f}%"


def _money(x) -> str:
    if x is None:
        return ""
    x = Decimal(x)
    return f"-${-x:,.2f}" if x < 0 else f"${x:,.2f}"


def _esc(s) -> str:
    return "" if s is None else str(s).replace("|", "\\|")


def write_report(results: list[Result], run_at: datetime) -> str:
    counts = {s: sum(r.status == s for r in results) for s in ICON}
    fails = [r for r in results if r.status == "FAIL"]
    warns = [r for r in results if r.status == "WARN"]
    infos = [r for r in results if r.status == "INFO"]

    verdict = (
        f"❌ **{len(fails)} check(s) failed.** Do not use this data for analysis until resolved."
        if fails else
        "✅ **No failures.** The data is fit for analysis, with the known issues below."
    )

    L = []
    L += ["# Data-Quality Report",
          "",
          f"Generated by `src/validate.py` on {run_at:%Y-%m-%d %H:%M} · "
          f"Dataset: CMS DE-SynPUF Sample 2 (synthetic) · Database: `{DB_PATH.name}` · {len(results)} checks",
          "",
          f"**{ICON['PASS']} {counts['PASS']} passed · {ICON['WARN']} {counts['WARN']} known issues · "
          f"{ICON['FAIL']} {counts['FAIL']} failed · {ICON['INFO']} {counts['INFO']} informational**",
          "",
          verdict,
          "",
          "**How to read this:** *error* checks must be zero. *Warn* checks are known, documented "
          "data issues; the rows are kept and flagged, and the check fails only if the rate rises "
          "above its tolerance. *Info* checks give context and never fail.",
          ""]

    if fails:
        L += ["## ❌ Failures", "",
              "| Check | What it tests | Rows | % | $ | Detail |", "|---|---|--:|--:|--:|---|"]
        L += [f"| `{r.check.id}` | {r.check.description} | {_n(r.violations)} | {_pct(r)} | "
              f"{_money(r.amount)} | {_esc(r.detail)} |" for r in fails]
        L += [""]

    if warns:
        L += ["## ⚠️ Known issues (kept and flagged)", "",
              "| Check | Issue | Rows | % of rows | $ on those rows | Fails above | Reference |",
              "|---|---|--:|--:|--:|--:|---|"]
        L += [f"| `{r.check.id}` | {r.check.description} | {_n(r.violations)} | {_pct(r)} | "
              f"{_money(r.amount)} | {r.check.fail_above_pct}% | {r.check.reference} |" for r in warns]
        L += [""]

    if infos:
        L += ["## ℹ️ Context for analysts", "",
              "| Check | What it shows | Rows | % of rows | $ | Detail |", "|---|---|--:|--:|--:|---|"]
        L += [f"| `{r.check.id}` | {r.check.description} | {_n(r.violations)} | {_pct(r)} | "
              f"{_money(r.amount)} | {_esc(r.detail)} |" for r in infos]
        L += [""]

    L += ["## All checks by category", ""]
    for cat in dict.fromkeys(r.check.category for r in results):
        L += [f"### {cat.replace('_', ' ').title()}", "",
              "| | Check | Table | What it tests | Violations | Detail |", "|---|---|---|---|--:|---|"]
        L += [f"| {ICON[r.status]} | `{r.check.id}` | `{r.check.table}` | {r.check.description} | "
              f"{_n(r.violations)} | {_esc(r.detail)} |"
              for r in results if r.check.category == cat]
        L += [""]

    L += ["## Caveats", "",
          "- **Synthetic data.** CMS synthesis weakens real relationships between variables; "
          "results demonstrate method, not clinical truth.",
          "- **Top-coded costs.** Payments are rounded and capped by CMS, so the true high-cost tail is hidden. "
          "High-cost flags use Tukey fences on log(cost), not mean ± standard deviation; "
          "the extreme fence sits above the CMS cap, so no extreme outliers survive top-coding.",
          "- **Orphan segments** have no date, so yearly totals sum to slightly less than the all-time total "
          "(see `ORPHAN_SEGMENT_OUTPATIENT`).",
          "- **No carrier (physician) claims** are included, so cost per member is understated.",
          ""]

    REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    REPORT_PATH.write_text("\n".join(L), encoding="utf-8")
    return verdict


def main() -> int:
    if not DB_PATH.exists():
        print(f"{DB_PATH} not found. Run ingest.py and clean.py first.")
        return 1

    con = connect_db()  # write access: results are stored in qa.check_results
    run_at = datetime.now()
    run_id = uuid.uuid4().hex[:12]

    results = [run_check(con, c) for c in CHECKS]
    save_history(con, run_id, run_at, results)
    con.close()
    write_report(results, run_at)

    for r in results:
        if r.status in {"FAIL", "WARN"}:
            print(f"  {r.status:<4}  {r.check.id:<30} {_n(r.violations):>10} {_pct(r):>8}  {_esc(r.detail)}")
    counts = {s: sum(r.status == s for r in results) for s in ICON}
    print(f"\n{len(results)} checks: {counts['PASS']} pass, {counts['WARN']} warn, "
          f"{counts['FAIL']} fail, {counts['INFO']} info  (run {run_id})")
    print(f"Report: {REPORT_PATH.relative_to(REPORT_PATH.parent.parent)}")
    return 1 if counts["FAIL"] else 0


if __name__ == "__main__":
    sys.exit(main())
